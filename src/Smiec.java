public class Smiec {
    String nazwa;
    String docelowyKosz;
    boolean czyBrudny;
    boolean czyZlozony;
    public Smiec(String nazwa, String docelowyKosz, boolean czyBrudny, boolean czyZlozony){
        this.nazwa = nazwa;
        this.docelowyKosz = docelowyKosz;
        this.czyBrudny = czyBrudny;
        this.czyZlozony = czyZlozony;
    }
}
